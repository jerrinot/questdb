    // ========================
    // Count-only mode
    // ========================

    @Test
    public void testCountOnlyIntGt() throws Exception {
        // col0 > 5, count-only
        int[] data = {3, 7, 5, 10, 1, 6};
        IrDecoder.Instruction[] instructions = ir(
                insn(IMM, I4_TYPE, 5, 0),
                insn(MEM, I4_TYPE, 0, 0),
                insn(GT, 0, 0, 0),
                insn(RET, 0, 0, 0)
        );

        long colData = allocIntColumn(data);
        long colPtrArray = Unsafe.malloc(8, MemoryTag.NATIVE_DEFAULT);
        Unsafe.getUnsafe().putLong(colPtrArray, colData);

        try {
            LoweredProgram prog = IrLowering.lower(instructions, SCALAR_OPTIONS);
            ScalarBytecodeFilterCompiler.ScalarFilterBody filter = ScalarBytecodeFilterCompiler.compile(prog);

            long count = filter.countRows(colPtrArray, 1, 0, 0, 0, data.length);

            // Interpreter oracle
            long expectedCount = interpreterCount(instructions, SCALAR_OPTIONS, colPtrArray, 1, 0, 0, 0, data.length);

            Assert.assertEquals(expectedCount, count);
        } finally {
            Unsafe.free(colData, (long) data.length * Integer.BYTES, MemoryTag.NATIVE_DEFAULT);
            Unsafe.free(colPtrArray, 8, MemoryTag.NATIVE_DEFAULT);
        }
    }

