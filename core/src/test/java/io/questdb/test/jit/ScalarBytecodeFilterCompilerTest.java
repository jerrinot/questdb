    @Test
    public void testMixedIntFloatComparison() throws Exception {
        // col0 (I4) > 2.5 (F8) — the serializer promotes I4 to F8
        // IR: IMM F8 2.5, MEM I4 col0, GT, RET
        IrDecoder.Instruction[] instructions = ir(
                new IrDecoder.Instruction(IMM, F8_TYPE, Double.doubleToRawLongBits(2.5), 0),
                insn(MEM, I4_TYPE, 0, 0),
                insn(GT, 0, 0, 0),
                insn(RET, 0, 0, 0)
        );

        // This is a scalar program (mixed sizes), no null checks
        int options = (3 << 1); // log2(8)=3, scalar hint
        assertParityIntCol(new int[]{1, 3, 2, 5, 0}, instructions, options);
    }

    @Test
    public void testFloatConstantComparison() throws Exception {
        // col0 (F4) > 3.14 (F4)
        IrDecoder.Instruction[] instructions = ir(
                new IrDecoder.Instruction(IMM, F4_TYPE, Double.doubleToRawLongBits(3.14), 0),
                new IrDecoder.Instruction(MEM, F4_TYPE, 0, 0),
                insn(GT, 0, 0, 0),
                insn(RET, 0, 0, 0)
        );

        int options = (2 << 1) | (1 << 4); // log2(4), single-size
        float[] data = {1.0f, 4.0f, 3.14f, 5.0f, 2.0f};
        long colData = Unsafe.malloc((long) data.length * Float.BYTES, MemoryTag.NATIVE_DEFAULT);
        long colPtrArray = Unsafe.malloc(8, MemoryTag.NATIVE_DEFAULT);
        long outputBuf = Unsafe.malloc((long) data.length * Long.BYTES, MemoryTag.NATIVE_DEFAULT);
        long expectedBuf = Unsafe.malloc((long) data.length * Long.BYTES, MemoryTag.NATIVE_DEFAULT);
        for (int i = 0; i < data.length; i++) {
            Unsafe.getUnsafe().putFloat(colData + (long) i * Float.BYTES, data[i]);
        }
        Unsafe.getUnsafe().putLong(colPtrArray, colData);

        try {
            long expected = interpreterFilter(instructions, options, colPtrArray, 1, 0, 0, 0, expectedBuf, data.length);

            LoweredProgram prog = IrLowering.lower(instructions, options);
            ScalarBytecodeFilterCompiler.ScalarFilterBody filter = ScalarBytecodeFilterCompiler.compile(prog);
            if (filter == null) {
                return; // unsupported, skip
            }
            long actual = filter.filterRows(colPtrArray, 1, 0, 0, 0, outputBuf, data.length);

            Assert.assertEquals("row count mismatch", expected, actual);
        } finally {
            Unsafe.free(colData, (long) data.length * Float.BYTES, MemoryTag.NATIVE_DEFAULT);
            Unsafe.free(colPtrArray, 8, MemoryTag.NATIVE_DEFAULT);
            Unsafe.free(outputBuf, (long) data.length * Long.BYTES, MemoryTag.NATIVE_DEFAULT);
            Unsafe.free(expectedBuf, (long) data.length * Long.BYTES, MemoryTag.NATIVE_DEFAULT);
        }
    }

    // ========================
    // Byte (I1) type tests
