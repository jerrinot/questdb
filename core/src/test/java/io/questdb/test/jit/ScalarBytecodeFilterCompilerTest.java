    private static long allocIntColumn(int[] data) {
        long mem = Unsafe.malloc((long) data.length * Integer.BYTES, MemoryTag.NATIVE_DEFAULT);
        for (int i = 0; i < data.length; i++) {
            Unsafe.getUnsafe().putInt(mem + (long) i * Integer.BYTES, data[i]);
        }
        return mem;
    }

    private static long interpreterFilter(
            IrDecoder.Instruction[] instructions, int options,
            long colPtrArray, long colCount, long varSizeAux,
            long varsAddr, long varsCount,
            long outputBuf, int rowCount
    ) throws Exception {
        try (MemoryCARW irMem = Vm.getCARWInstance(1024, 1, MemoryTag.NATIVE_JIT)) {
            writeIr(irMem, instructions);
            VectorFilterInterpreter interp = new VectorFilterInterpreter();
            interp.compile(irMem, options);
            return interp.filter(colPtrArray, colCount, varSizeAux, varsAddr, varsCount, outputBuf, rowCount);
        }
    }

    private static long interpreterCount(
            IrDecoder.Instruction[] instructions, int options,
            long colPtrArray, long colCount, long varSizeAux,
            long varsAddr, long varsCount, int rowCount
    ) throws Exception {
        try (MemoryCARW irMem = Vm.getCARWInstance(1024, 1, MemoryTag.NATIVE_JIT)) {
            writeIr(irMem, instructions);
            VectorFilterInterpreter interp = new VectorFilterInterpreter();
            interp.compile(irMem, options);
            return interp.filterCount(colPtrArray, colCount, varSizeAux, varsAddr, varsCount, rowCount);
        }
    }

    private static void writeIr(MemoryCARW mem, IrDecoder.Instruction[] instructions) {
        for (IrDecoder.Instruction insn : instructions) {
            mem.putInt(insn.opcode());
            mem.putInt(insn.type());
            mem.putLong(insn.payloadLo());
            mem.putLong(insn.payloadHi());
        }
    }

    private static IrDecoder.Instruction[] ir(IrDecoder.Instruction... instructions) {
        return instructions;
    }

    private static IrDecoder.Instruction insn(int opcode, int type, long lo, long hi) {
        return new IrDecoder.Instruction(opcode, type, lo, hi);
    }
